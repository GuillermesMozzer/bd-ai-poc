export function buildScheduleVersionKpis(versions: ScheduleVersion[]): ScheduleVersionKpi[] {
  const active = versions.filter((v) => v.status === 'Frozen' || v.status === 'Published').length;
  const pending = versions.filter((v) => v.approvalStatus === 'Pending Approval').length;
  const total = versions.length;
  const thisMonth = versions.filter((v) => {
    const now = new Date();
    const created = new Date(v.createdAt);
    return created.getFullYear() === now.getFullYear() && created.getMonth() === now.getMonth();
  }).length;

  return [
    {
      key: 'active',
      label: 'Active Baselines',
      value: active,
      helperText: 'Published or Frozen schedule versions',
      tone: 'success',
      icon: 'baseline',
    },
    {
      key: 'pending',
      label: 'Pending Approval',
      value: pending,
      helperText: 'Awaiting planner confirmation',
      tone: pending > 0 ? 'warning' : 'neutral',
      icon: 'pending',
    },
    {
      key: 'total',
      label: 'Total Versions',
      value: total,
      helperText: 'All schedule versions across cycles',
      tone: 'info',
      icon: 'versions',
    },
    {
      key: 'thisMonth',
      label: 'Created This Month',
      value: thisMonth,
      helperText: 'New schedule versions this month',
      tone: 'neutral',
      icon: 'lines',
    },
  ];
}

