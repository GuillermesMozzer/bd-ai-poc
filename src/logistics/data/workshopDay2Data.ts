function stage(status, owner, opts = {}) {
  return {
    status, // not_started | in_progress | waiting | blocked | complete
    owner_user_id: owner,
    started_at: opts.started_at ?? null,
    expected_at: opts.expected_at ?? null,
    completed_at: opts.completed_at ?? null,
    delay_reason: opts.delay_reason ?? null,
    notes: opts.notes ?? null,
  };
}

/** @param {string} currentStageId */
function buildStages(currentStageId, overrides = {}) {
  const idx = READINESS_STAGE_IDS.indexOf(currentStageId);
  return READINESS_STAGE_IDS.map((id, i) => {
    if (overrides[id]) return { stage_id: id, ...overrides[id] };
    if (i < idx) return { stage_id: id, ...stage('complete', 'USR-wh-lead', { completed_at: '2026-07-09T10:00:00-06:00' }) };
    if (i === idx) return { stage_id: id, ...stage('in_progress', 'USR-wh-lead') };
    return { stage_id: id, ...stage('not_started', null) };
  });
}

